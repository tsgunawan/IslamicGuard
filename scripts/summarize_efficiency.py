"""Generate a reproducible efficiency table from experiment run artifacts.

The report only emits quantities actually recorded in each run.  A missing measurement is
rendered as ``not captured`` rather than inferred from unrelated timings.

Example:
    python scripts/summarize_efficiency.py \
        --run-id 20260920-0426_Qwen__Qwen3-8B_B0_t15_benchmark_s42 \
        --out results/tables/t18_efficiency_profile.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[1]


def load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.exists() or not path.read_text(encoding="utf-8").strip():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines()]


def fmt_seconds(value: float | None) -> str:
    return "not captured" if value is None else f"{value:.1f} s"


def fmt_number(value: float | int | None, suffix: str = "") -> str:
    return "not captured" if value is None else f"{value}{suffix}"


def summarize_run(run_dir: Path) -> dict[str, Any]:
    config = (run_dir / "config.yaml").read_text(encoding="utf-8")
    metrics = load_json(run_dir / "metrics.json")
    timing = load_json(run_dir / "timing.json")
    responses = load_jsonl(run_dir / "responses.jsonl")
    traces = load_jsonl(run_dir / "guardrail_traces.jsonl")
    gpu_samples = load_jsonl(run_dir / "gpu_samples.jsonl")

    def config_value(key: str) -> str:
        prefix = f"{key}:"
        for line in config.splitlines():
            if line.startswith(prefix):
                return line.split(":", 1)[1].strip()
        return "unknown"

    gen_latencies = timing.get("generation_latencies_ms", [])
    if not gen_latencies:
        gen_latencies = [response.get("latency_ms") for response in responses]
        gen_latencies = [value for value in gen_latencies if isinstance(value, (int, float))]
    validation_latencies = [trace.get("validation_latency_ms") for trace in traces]
    validation_latencies = [value for value in validation_latencies if isinstance(value, (int, float))]
    peak_mib = max((sample.get("memory_used_mib") for sample in gpu_samples), default=None)
    mean_utilization = (
        round(sum(sample["gpu_utilization_pct"] for sample in gpu_samples) / len(gpu_samples), 1)
        if gpu_samples
        else None
    )

    return {
        "run_id": run_dir.name,
        "model": config_value("model"),
        "condition": config_value("condition"),
        "n_items": metrics.get("n_items"),
        "generation_seconds": round(sum(gen_latencies) / 1000, 3) if gen_latencies else None,
        "generation_reused_from": metrics.get("derived_from_source_run"),
        "validator_seconds": round(sum(validation_latencies) / 1000, 3) if validation_latencies else None,
        "mean_completion_tokens": metrics.get("mean_completion_tokens"),
        "mean_retrieved_per_item": metrics.get("mean_retrieved_per_item"),
        "peak_gpu_mib": peak_mib,
        "gpu_sample_count": len(gpu_samples),
        "mean_gpu_utilization_pct": mean_utilization,
    }


def render_markdown(rows: list[dict[str, Any]]) -> str:
    lines = [
        "# T18 — Automated efficiency profile",
        "",
        "Generated by `scripts/summarize_efficiency.py` from saved run artifacts. A `not captured`",
        "cell is an explicit measurement gap, never a hand-entered estimate.",
        "",
        "| Run | Model | Condition | Items | Generation time | Generation provenance | Validator time | Mean completion tokens | Mean retrieved/item | Peak GPU memory | GPU samples | Mean GPU utilization |",
        "|---|---|---|---:|---:|---|---:|---:|---:|---:|---:|---:|",
    ]
    for row in rows:
        lines.append(
            "| {run_id} | {model} | {condition} | {n_items} | {generation} | {provenance} | {validator} | "
            "{tokens} | {retrieved} | {peak} | {samples} | {utilization} |".format(
                run_id=row["run_id"],
                model=row["model"],
                condition=row["condition"],
                n_items=fmt_number(row["n_items"]),
                generation=fmt_seconds(row["generation_seconds"]),
                provenance=(f"reused from `{row['generation_reused_from']}`" if row["generation_reused_from"] else "executed"),
                validator=fmt_seconds(row["validator_seconds"]),
                tokens=fmt_number(row["mean_completion_tokens"]),
                retrieved=fmt_number(row["mean_retrieved_per_item"]),
                peak=fmt_number(row["peak_gpu_mib"], " MiB"),
                samples=fmt_number(row["gpu_sample_count"]),
                utilization=fmt_number(row["mean_gpu_utilization_pct"], "%"),
            )
        )
    lines.extend(
        [
            "",
            "Notes: generation and validator time are sums of per-item recorded latencies. Derived B2 "
            "rows reuse their B5 generation and must not be added as separate GPU compute. "
            "Retrieval-wall-clock and end-to-end wall-clock are reported only when a run explicitly records them; "
            "the current artifacts do not, so this report does not fabricate either value.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-id", action="append", required=True, help="Run directory name under runs/")
    parser.add_argument("--out", type=Path, required=True, help="Markdown report destination")
    args = parser.parse_args()

    rows = [summarize_run(REPO_ROOT / "runs" / run_id) for run_id in args.run_id]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render_markdown(rows), encoding="utf-8")
    print(f"wrote {args.out} for {len(rows)} runs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
